function build_mltbx()
%BUILD_MLTBX  Repackage code/ as the .mltbx that sits beside this file.
%
%   build_mltbx
%
%   RUN THIS WHENEVER THE MODEL CHANGES.  The .mltbx is a COPY of code/, not a
%   pointer to it, so without a rebuild the "install into the Apps tab" route
%   ships the old model while "Open the GUI (Windows).bat" -- which runs code/
%   in place -- ships the new one.  Two people would then get different
%   numbers from the same folder, and nothing in the window would say so.
%   Nothing does this automatically.
%
%   The add-on identifier is FIXED.  It is the same GUID v1 and v2 were built
%   with, so installing this REPLACES the installed add-on instead of sitting
%   beside it.  That is deliberate: every version shares its function names, so
%   two on the path at once would silently run whichever came first.  Do not
%   generate a new GUID.
%
%   Bump ToolboxVersion below when the physics changes.

here  = fileparts(mfilename('fullpath'));
stage = fullfile(tempdir, 'phytagel_tbx_build');

if ~isfolder(fullfile(here,'code','Heatmodel','matlab'))
    error('build_mltbx:code', ...
          'no code folder beside this file -- expected %s', fullfile(here,'code'));
end

if isfolder(stage), rmdir(stage,'s'); end
mkdir(stage);
copyfile(fullfile(here,'code','*'), stage);

% The Apps-tab button.  MATLAB reads this on install; it is what puts
% "heat_gui" in the APPS tab.  It lives only in the package, not in code/,
% because it means nothing to someone running the .bat.
fid = fopen(fullfile(stage,'DesktopToolset.xml'),'w');
if fid < 0, error('build_mltbx:write','cannot write into %s', stage); end
fprintf(fid, '%s\n', ...
'<?xml version="1.0" encoding="UTF-8"?>', ...
'<toolset id="user_apps_toolset" template="false">', ...
['    <tool app_file_path="heat_gui.m" handler_class="com.mathworks.deploy' ...
 'ment.desktop.toolstrip.ToolboxToolSetExtensionHandler" id="139570c1-27de' ...
 '-44ea-a979-55c17a2b54d0:heat_gui.m" label="heat_gui" quick_access_eligib' ...
 'le="false" toolset_id="user_apps_toolset">'], ...
'        <callback>heat_gui</callback>', ...
'        <summary></summary>', ...
'        <description></description>', ...
'        <icon filename="matlab_app_generic_icon_24" id="app"/>', ...
'        <icon filename="matlab_app_generic_icon_16"/>', ...
'        <parent_tool id="my_apps" toolset_id="apps_toolset"/>', ...
'    </tool>', ...
'</toolset>');
fclose(fid);

opts = matlab.addons.toolbox.ToolboxOptions(stage, ...
        '7b3f1c2e-9a4d-4e61-8f27-c05d3a6b1e94');   % see the header -- fixed
opts.ToolboxName    = 'Phytagel Heat GUI';
opts.ToolboxVersion = '2.1.0';
opts.AuthorName     = 'Tadhg Stuckey';
opts.Summary = ['2.45 GHz monopole on a Phytagel phantom, with the antenna ' ...
                'immersed in the bath.'];
opts.Description = [ ...
'v2.1.  The antenna is in the BATH, not in air, and the feed current RETURNS' newline ...
'along the coax braid instead of stopping dead.' newline newline ...
'v1 solved the antenna radiating into air above the gel, which sent 99.6% of' newline ...
'the delivered power into the gel.  The bench photographs show it fully' newline ...
'immersed, and a bath of nearly the same permittivity as the gel takes most of' newline ...
'the power instead:' newline ...
'  air above       99.6% into the gel' newline ...
'  tap/DI bath     46.4% into the gel, 51.3% into the bath' newline ...
'  0.9% saline     39.2% into the gel, 60.7% into the bath' newline newline ...
'v2.1 adds two things.  There is no longer a fictitious point charge at the' newline ...
'feed, so the maps have no grey wedge blanked out of them and the peak' newline ...
'temperature no longer depends on the grid (1.2% across three grids, against' newline ...
'32% before).  And the drive can be pulsed: set a period and a duty cycle.' newline newline ...
'Set "above the gel" to air and the braid arm to 0 to reproduce v1 exactly.' newline newline ...
'Needs base MATLAB only.  Open from the APPS tab.'];
opts.MinimumMatlabRelease = 'R2022b';
opts.MaximumMatlabRelease = '';
opts.SupportedPlatforms = struct('Win64',true,'Maci64',true, ...
                                 'Glnxa64',true,'MatlabOnline',true);
opts.ToolboxMatlabPath = {stage, ...
                          fullfile(stage,'Heatmodel','matlab'), ...
                          fullfile(stage,'matlab')};
opts.OutputFile = fullfile(here,'Phytagel Heat GUI v2.mltbx');

matlab.addons.toolbox.packageToolbox(opts);
d = dir(opts.OutputFile);
fprintf('wrote %s  (%.0f kB, version %s)\n', opts.OutputFile, d.bytes/1024, ...
        opts.ToolboxVersion);
rmdir(stage,'s');
end
